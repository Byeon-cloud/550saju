/** 일주 한자 → IljuAnimal 변환 (60갑자 모두 자동 생성) */
export function getIljuAnimal(ilju: string): IljuAnimal | null {
  if (!ilju || ilju.length !== 2) return null;
  const gan = ilju[0];
  const zhi = ilju[1];
  const color = GAN_COLOR[gan];
  const animal = ZHI_ANIMAL[zhi];
  const ko = ILJU_KO_READ[ilju];
  if (!color || !animal || !ko) return null;

  return {
    ko,
    hanja: ilju,
    animal: animal.ko,
    animalEmoji: animal.emoji,
    colorKo: color.ko,
    colorHex: color.hex,
    nickname: `${color.ko} ${animal.ko}`,
    hint: ILJU_HINT[ilju] || `${color.ko} ${animal.ko}의 본질을 가진 일주`,
  };
}

