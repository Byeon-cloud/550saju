export function buildUserPrompt(
  contentType: string,
  ctx: { dateStr: string; weekday: string; season: string },
  ganji: DayGanji,
  formatHint?: string,
): string {
  const guide = TYPE_GUIDE[contentType] ?? TYPE_GUIDE.knowledge;
  const fmt = formatHint
    ? `\n[구성 힌트] 이번 글은 이 형태로 써라 (틀 매번 바꾸는 중): ${formatHint}`
    : "";
  return `오늘: ${ctx.dateStr}, 계절: ${ctx.season}
오늘 기운(내부 참고): ${ganji.ko}일 — '${ganji.ganOh}' 기운이 도는 날 (${ganji.animal}띠의 날). 독자에겐 간지 글자 대신 '오늘은 ~한 기운' 식으로 쉽게.

콘텐츠 타입: ${contentType}
가이드: ${guide}${fmt}

시스템 규칙(짧은 본문, 마침표/한자 최소, 스친이 호칭, 안 딱딱하게, 매크로 티 금지)을 지켜서 이 타입 글 1개를 JSON으로. content_type엔 "${contentType}" 그대로.`;
}
