/* 연관 키워드가 운세를 찾는 말인지 가르는 규칙. 연관 키워드 상위는 로또, 복권, 별자리 같은 말이 많아서
 *   새 키워드 발굴에는 이 규칙을 통과한 것만 따로 본다. 별자리와 타로는 다른 점술이라 뺀다(사주 하나로 집중). */
const FORTUNE_RE = /운세|사주|궁합|꿈|해몽|만세력|토정|삼재|팔자|일주|대운|용신|오행|십성|십신|격국|신살|도화살|역마살|홍염살|괴강살|백호살|원진|띠|운$|철학관|점집|신점|재회|인연|태몽|길몽|흉몽|손없는날|이사날짜/;
const NOT_FORTUNE_RE = /별자리|자리운세|타로|로또|복권|당첨/;
const isFortuneIntent = (kw) => { const s = String(kw).replace(/\s+/g, ''); return FORTUNE_RE.test(s) && !NOT_FORTUNE_RE.test(s); };

/* 공백 제거 + 대문자. 네이버 키워드 도구 relKeyword 와 맞춰 보는 열쇠 */
const normalize = (s) => String(s).replace(/\s+/g, '').toUpperCase();

/* 네이버로 보낼 힌트 키워드 표: 열쇠 → { send(공백 뺀 원래 표기), categories, originals } */
function uniqueHints() {
  const map = new Map();
  for (const c of CATEGORIES) {
    for (const k of c.keywords) {
      const key = normalize(k);
      if (!map.has(key)) map.set(key, { key, send: String(k).replace(/\s+/g, ''), categories: [], originals: [] });
      const e = map.get(key);
      if (!e.categories.includes(c.id)) e.categories.push(c.id);
      if (!e.originals.includes(k)) e.originals.push(k);
    }
  }
  return [...map.values()];
}

/* 두 묶음에 같은 키워드가 있으면 알려 준다(합이 겹치는 것을 막기 위해) */
function checkOverlap() {
  return uniqueHints().filter((h) => h.categories.length > 1).map((h) => `${h.originals.join('/')} → ${h.categories.join(', ')}`);
}

